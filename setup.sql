DROP TABLE IF EXISTS dbo.fact_sales;
DROP TABLE IF EXISTS dbo.dim_product;
DROP TABLE IF EXISTS dbo.dim_store;
GO

CREATE TABLE dbo.dim_product (
    product_id   VARCHAR(10)  NOT NULL PRIMARY KEY,
    product_name VARCHAR(100) NOT NULL,
    category     VARCHAR(50)  NOT NULL,
    unit_cost    INT          NOT NULL
);

CREATE TABLE dbo.dim_store (
    store_id   VARCHAR(10)  NOT NULL PRIMARY KEY,
    store_name VARCHAR(100) NOT NULL,
    city       VARCHAR(50)  NOT NULL,
    store_type VARCHAR(50)  NOT NULL
);

CREATE TABLE dbo.fact_sales (
    transaction_id   INT         NOT NULL PRIMARY KEY,
    transaction_date DATE        NOT NULL,
    store_id         VARCHAR(10) NOT NULL REFERENCES dbo.dim_store(store_id),
    customer_id      VARCHAR(10) NOT NULL,
    product_id       VARCHAR(10) NOT NULL REFERENCES dbo.dim_product(product_id),
    quantity         INT         NOT NULL,
    unit_price       INT         NOT NULL,
    discount         INT         NOT NULL,
    net_sales        INT         NOT NULL   -- quantity * unit_price - discount
);
GO

